async function callGateway(apiKey: string, body: unknown) {
  const res = await fetch(GATEWAY_URL, {
    method: "POST",
    headers: { "Content-Type": "application/json", "Lovable-API-Key": apiKey },
    body: JSON.stringify(body),
  });
  if (!res.ok) {
    const text = await res.text();
    throw new Error(`AI Gateway ${res.status}: ${text}`);
  }
  const json = (await res.json()) as { choices: Array<{ message: { content: string } }> };
  return JSON.parse(json.choices[0]?.message?.content ?? "{}");
}

export const analyzeVoice = createServerFn({ method: "POST" })
  .inputValidator((v: unknown) => InputSchema.parse(v))
  .handler(async ({ data }): Promise<DetectionReport> => {
    const apiKey = process.env.LOVABLE_API_KEY;
    if (!apiKey) throw new Error("LOVABLE_API_KEY not configured");

    const audioContent = {
      type: "input_audio",
      input_audio: { data: data.audioBase64, format: data.format },
    };

    const [parsed, deepfake, human, antispoof] = await Promise.all([
      callGateway(apiKey, {
        model: MODEL,
        messages: [
          { role: "system", content: SYSTEM_PROMPT },
          {
            role: "user",
            content: [
              {
                type: "text",
                text: "Analyse this audio and return JSON matching the schema. Provide a one-line headline, short reasoning, per-finding severity tags, and supporting evidence with quotes/observations.",
              },
              audioContent,
            ],
          },
        ],
        response_format: {
          type: "json_schema",
          json_schema: { name: "voice_analysis", strict: true, schema: RESPONSE_SCHEMA },
        },
      }) as Promise<{
        transcript: string;
        aiVoiceScore: number;
        fraudScore: number;
        confidence: number;
        headline: string;
        reasoning: string;
        acousticFindings: Finding[];
        linguisticFindings: Finding[];
        supportingEvidence: Evidence[];
      }>,
      callGateway(apiKey, {
        model: MODEL,
        messages: [
          { role: "system", content: DEEPFAKE_SYSTEM_PROMPT },
          {
            role: "user",
            content: [
              { type: "text", text: "Run the specialised deepfake detector on this audio. Return JSON matching the schema." },
              audioContent,
            ],
          },
        ],
        response_format: {
          type: "json_schema",
          json_schema: { name: "deepfake_analysis", strict: true, schema: DEEPFAKE_SCHEMA },
        },
      }) as Promise<{
        deepfakeScore: number;
        humanLikelihood: number;
        suspectedFamily: string;
        vocoderFingerprint: string;
        modelNotes: string;
        artifacts: DeepfakeArtifact[];
        segments: LocalizedSegment[];
        estimatedDuration: number;
      }>,
      callGateway(apiKey, {
        model: MODEL,
        messages: [
          { role: "system", content: HUMAN_SYSTEM_PROMPT },
          {
            role: "user",
            content: [
              { type: "text", text: "Run the human-voice verifier on this audio. Return JSON matching the schema." },
              audioContent,
            ],
          },
        ],
        response_format: {
          type: "json_schema",
          json_schema: { name: "human_verifier", strict: true, schema: HUMAN_SCHEMA },
        },
      }) as Promise<{
        humanScore: number;
        notes: string;
        biosignals: HumanBiosignal[];
      }>,
      callGateway(apiKey, {
        model: MODEL,
        messages: [
          { role: "system", content: ANTISPOOF_SYSTEM_PROMPT },
          {
            role: "user",
            content: [
              { type: "text", text: "Run the anti-spoofing / liveness detector on this audio. Return JSON matching the schema." },
              audioContent,
            ],
          },
        ],
        response_format: {
          type: "json_schema",
          json_schema: { name: "anti_spoofing", strict: true, schema: ANTISPOOF_SCHEMA },
        },
      }) as Promise<{
        spoofScore: number;
        livenessScore: number;
        channelProfile: string;
        notes: string;
        attackVectors: AttackVector[];
      }>,
    ]);

    // 4-specialist ensemble fusion on the AI-likelihood axis.
    const specialistScore = clamp(deepfake.deepfakeScore);
    const generalistScore = clamp(parsed.aiVoiceScore);
    const humanScore = clamp(human.humanScore);
    const humanAsAi = 100 - humanScore;
    const spoofScore = clamp(antispoof.spoofScore);
    const livenessScore = clamp(antispoof.livenessScore);
    const livenessAsAi = 100 - livenessScore;
    // Attack-driven AI axis: neural-TTS + voice-conversion are the synthesis vectors
    // (replay / splicing / channel push fraudScore, not aiVoiceScore).
    const vec = (name: string) =>
      clamp(
        antispoof.attackVectors?.find((v) => v.name.toLowerCase().includes(name))?.score ?? 0,
      );
    const synthesisAttack = Math.max(vec("tts"), vec("synthesis"), vec("conversion"), vec("vc"));

    // Weighted fusion: specialist 40%, human-verifier 25%, anti-spoof synthesis 20%, generalist 15%.
    const aiVoiceScore = Math.round(
      specialistScore * 0.4 +
        humanAsAi * 0.25 +
        Math.max(synthesisAttack, livenessAsAi) * 0.2 +
        generalistScore * 0.15,
    );

    // Calibrated probability via logistic — sharpens confident scores, softens borderline.
    const logit = (aiVoiceScore - 50) / 12;
    const calibratedAiProbability = Math.round((1 / (1 + Math.exp(-logit))) * 100);

    // Fraud fuses linguistic fraudScore with non-synthesis attack vectors.
    const nonSynthAttack = Math.max(vec("replay"), vec("splic"), vec("channel"));
    const fraudScore = clamp(Math.max(parsed.fraudScore, nonSynthAttack * 0.6 + spoofScore * 0.2));

    // Agreement / confidence across all 4 AI-axis scores.
    const axis = [specialistScore, humanAsAi, generalistScore, Math.max(synthesisAttack, livenessAsAi)];
    const mean = axis.reduce((a, b) => a + b, 0) / axis.length;
    const variance = axis.reduce((s, v) => s + (v - mean) ** 2, 0) / axis.length;
    const stdev = Math.sqrt(variance);
    const originConfidence = clamp(100 - stdev * 1.8);

    let originLabel: VoiceOrigin["label"];
    if (aiVoiceScore >= 60 && originConfidence >= 55) originLabel = "ai";
    else if (aiVoiceScore <= 30 && originConfidence >= 55) originLabel = "human";
    else originLabel = "uncertain";

    let verdict: DetectionReport["verdict"] = "authentic";
    if (aiVoiceScore >= 65 && fraudScore >= 55) verdict = "likely_fraud";
    else if (aiVoiceScore >= 65) verdict = "ai_synthesized";
    else if (fraudScore >= 55 || aiVoiceScore >= 45 || spoofScore >= 60) verdict = "suspicious";

    const rawSegments = Array.isArray(deepfake.segments) ? deepfake.segments : [];
    const duration = Math.max(
      0,
      Number.isFinite(deepfake.estimatedDuration) ? deepfake.estimatedDuration : 0,
    );
    const segments: LocalizedSegment[] = rawSegments
      .filter((s) => Number.isFinite(s.start) && Number.isFinite(s.end) && s.end > s.start)
      .map((s) => ({
        start: Math.max(0, s.start),
        end: Math.max(s.start + 0.01, s.end),
        score: clamp(s.score),
        label: s.label ?? (clamp(s.score) >= 65 ? "synthetic" : clamp(s.score) >= 40 ? "suspicious" : "human"),
        note: s.note ?? "",
      }));

    return {
      transcript: parsed.transcript ?? "",
      aiVoiceScore,
      fraudScore,
      confidence: clamp(parsed.confidence),
      acousticFindings: parsed.acousticFindings ?? [],
      linguisticFindings: parsed.linguisticFindings ?? [],
      supportingEvidence: parsed.supportingEvidence ?? [],
      deepfakeAnalysis: {
        deepfakeScore: specialistScore,
        humanLikelihood: clamp(deepfake.humanLikelihood),
        suspectedFamily: deepfake.suspectedFamily ?? "Unknown",
        vocoderFingerprint: deepfake.vocoderFingerprint ?? "",
        modelNotes: deepfake.modelNotes ?? "",
        artifacts: deepfake.artifacts ?? [],
        segments,
        estimatedDuration: duration || (segments.at(-1)?.end ?? 0),
      },
      humanVerifier: {
        humanScore,
        biosignals: human.biosignals ?? [],
        notes: human.notes ?? "",
      },
      antiSpoofing: {
        spoofScore,
        livenessScore,
        attackVectors: (antispoof.attackVectors ?? []).map((v) => ({
          name: v.name,
          score: clamp(v.score),
          detail: v.detail,
        })),
        channelProfile: antispoof.channelProfile ?? "",
        notes: antispoof.notes ?? "",
      },
      voiceOrigin: {
        label: originLabel,
        confidence: originConfidence,
        aiScore: aiVoiceScore,
        humanScore: 100 - aiVoiceScore,
        calibratedAiProbability,
        agreement: {
          generalistAi: generalistScore,
          specialistDeepfake: specialistScore,
          humanVerifier: humanScore,
          antiSpoofing: Math.max(synthesisAttack, livenessAsAi),
        },
      },


      verdict,
      headline: parsed.headline ?? defaultHeadline(verdict),
      reasoning: parsed.reasoning ?? "",
      recommendedActions: buildActions(verdict),
    };
  });


function clamp(n: number) {
  if (!Number.isFinite(n)) return 0;
  return Math.max(0, Math.min(100, Math.round(n)));
}

function defaultHeadline(v: DetectionReport["verdict"]) {
  switch (v) {
    case "likely_fraud":
      return "Likely voice-fraud call detected";
    case "ai_synthesized":
      return "Voice appears AI-synthesised";
    case "suspicious":
      return "Suspicious signals detected";
    default:
      return "No strong fraud or synthesis indicators";
  }
}

function buildActions(v: DetectionReport["verdict"]): string[] {
  switch (v) {
    case "likely_fraud":
      return [
        "Do NOT act on any instructions in this call.",
        "Hang up and call the organisation back on a verified number.",
        "Report the call to your local anti-fraud authority.",
      ];
    case "ai_synthesized":
      return [
        "Voice appears synthetically generated — verify caller identity out-of-band.",
        "Ask a personal challenge question the real person would know.",
      ];
    case "suspicious":
      return [
        "Treat with caution; independently verify caller identity.",
        "Never share OTPs, passwords, or make payments based on this call.",
      ];
    default:
      return ["No strong indicators of fraud or synthesis detected. Stay vigilant."];
  }
}
